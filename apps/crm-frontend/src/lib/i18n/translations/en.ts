/** Recursively widen literal types to their base primitives. */
export type WidenLiterals<T> = T extends string
  ? string
  : T extends number
    ? number
    : T extends boolean
      ? boolean
      : T extends readonly (infer U)[]
        ? WidenLiterals<U>[]
        : { [K in keyof T]: WidenLiterals<T[K]> };

